NEW = "new"

# Classes whose failing poses are decided by round-off, and so differ between
# machines, not only between Linux and macOS: an exact-limit angle beyond the
# limit band (F, #632). Observed: the same commit's CI runners disagree on which
# of these cells fail. Their known cells are non-strict xfails until that issue
# makes the outcome reproducible; every other class is strict. The rescue (D)
# left this set when both backends came to share one deterministic definition
# (#622); a rescued solution that lands exactly on a limit is an F case
# (``_Pose.across_limit``). F stays after #624 made a limit inclusive up to
# round-off and #636 polished accepted general_6r solutions to machine
# precision. What is left is an exact-limit angle at a singular pose
# (sigma_min < 1e-4, a multiple root accurate to ~sqrt(round-off), where the
# polish declines), a Python-path general_6r solution that only the
# near-miss refinement recovered (accurate to its 1e-5 gate: a near-repeated
# root the repeated-root split does not engage on, #640), and the OpenArm SRS
# elbow sign. The side of the limit these land on follows the machine's LAPACK
# kernels, and the cells differ between Linux and macOS.
ROUNDOFF_CLASSES = frozenset({"F"})

# Known cells of a strict class that also differ between CI runners of one
# platform, as (direction, class, arm): non-strict like the round-off class,
# until the named issue makes them reproducible. Record them under the ``ci``
# key of the arm's ``cells`` (scripts/regen_native_parity.py).
#   fanuc_crx10ialp near_singular/8: a 4-fold near-repeated root the split does
#   not engage on, so Python recovers one branch only by the near-miss
#   refinement, 2e-3 from native's; whether the two are the same root by the
#   midpoint test follows the runner (#640).
RUNNER_DEPENDENT_CELLS = frozenset(
    {
        ("forward", "E", "fanuc_crx10ialp_ik"),
        ("reverse", "J", "fanuc_crx10ialp_ik"),
    }
)

# a. FK closure every returned solution must meet: the default policy's
# acceptance gate, documented in README ("How to read fk_residual"). Some
# solvers gate tighter internally, but the +-pi representative snap (#601)
# runs after that gate and may move a joint by up to 1e-6.
FK_TOL = DEFAULT_TOLERANCE_POLICY.subproblem_numerical

# a. How far a reported fk_residual may differ from ||FK(q) - T||_F at the
# returned q: round-off (measured within 5e-15), not the up-to-1e-6 moves of the
# +-pi snap and the limit clamp, after which the residual is re-measured (#645).
RESIDUAL_TOL = 1e-12

# a. How far outside a joint limit a default-mode solution may lie: not at
# all. A value within round-off of a limit is reported as exactly the limit
# (#624, docs/api.md "Joint limits"), so every returned angle is in limits.
LIMIT_SLACK = 0.0

# Two solutions are the same configuration within this L-infinity distance,
# every joint compared on the circle (a joint's 2*pi representative is fixed
# by the winding stage, not by the solver). 6R: the artifact conformance
# gate's radius. 7R: a solution samples a one-dimensional self-motion, and the
# polished families land their samples ~1e-3 apart between backends (#550);
# distinct samples are 2*pi/16 apart, so 1e-2 still tells them apart.
MATCH_TOL = {6: 1e-3, 7: 1e-2}

# d. A 7R pose whose configuration has sigma_min(J) below this is a kinematic
# singularity: the self-motion set gains a dimension there (an SRS elbow at
# full stretch frees q3 + q5), and each backend samples the extra continuum at
# its own points, so solution-for-solution coverage is not defined. Emptiness
# is still asserted there.
SEVEN_R_SINGULAR = 1e-6

# c. Oracle adjudication radius: a solution belongs to an oracle branch, and a
# branch is recovered by a backend, within this distance.
ADJ_TOL = 1e-3

# c. A 6R solution whose Jacobian has sigma_min at least this is a regular
# root; below it the solution may sit on a fold or a continuum, and only the
# oracle can tell.
REGULAR_SIGMA = 1e-3

# False makes every adjudication a live oracle run (the regeneration script).
USE_COMMITTED_ORACLE = True


# --------------------------------------------------------------------- arms


@cache
def _arm_paths() -> dict[str, str]:
    return {a.name: a.import_path for a in list_arms()}


def arm_names() -> list[str]:
    return sorted(_arm_paths())


def module(arm: str) -> Any:
    return importlib.import_module(_arm_paths()[arm])


def family(arm: str) -> str:
    """The solver family, with jointlock split by its locked-6R core."""
    solver = load_manifest()[arm].solver
    if solver == "jointlock.seven_r":
        from ssik._native import _HP_JOINTLOCK_ARMS

        return "jointlock.hp" if arm in _HP_JOINTLOCK_ARMS else "jointlock.rr"
    return solver


def ranges(kb: Any) -> tuple[Q, Q, NDArray[np.bool_]]:
    """Per-joint (lo, hi, has_limit); continuous joints span [-pi, pi]."""
    lo = np.array([j.limits[0] if j.limits else -np.pi for j in kb.joints], dtype=np.float64)
    hi = np.array([j.limits[1] if j.limits else np.pi for j in kb.joints], dtype=np.float64)
    has = np.array([j.limits is not None for j in kb.joints])
    return lo, hi, has


def sigma_min(kb: Any, q: Q) -> float:
    """Smallest of the six singular values of the spatial Jacobian."""
    return float(np.linalg.svd(kinbody_jacobian(kb, q), compute_uv=False)[5])


# -------------------------------------------------------------------- poses


def _rng(arm: str, stratum: str) -> np.random.Generator:
    return np.random.default_rng([SEED, *arm.encode(), *stratum.encode()])


def _uniform(arm: str, kb: Any, n: int) -> list[Q]:
    lo, hi, _ = ranges(kb)
    rng = _rng(arm, "uniform")
    return [rng.uniform(lo, hi) for _ in range(n)]


def _near_limit(arm: str, kb: Any, n: int) -> list[Q]:
    lo, hi, has = ranges(kb)
    rng = _rng(arm, "near_limit")
    limited = np.flatnonzero(has)
    out = []
    for k in range(n):
        q = rng.uniform(lo, hi)
        eps = LIMIT_OFFSETS[k % len(LIMIT_OFFSETS)]
        for i in rng.choice(
            limited, size=min(int(rng.integers(1, 4)), len(limited)), replace=False
        ):
            q[i] = lo[i] + eps if rng.random() < 0.5 else hi[i] - eps
        out.append(q)
    return out


def _at_pi(arm: str, kb: Any, n: int) -> list[Q]:
    lo, hi, _ = ranges(kb)
    wide = np.flatnonzero((lo <= -np.pi) | (hi >= np.pi))
    if not len(wide):
        return []
    rng = _rng(arm, "at_pi")
    values = (np.pi, -np.pi, np.pi - 1e-9, -np.pi + 1e-9)
    out = []
    for k in range(n):
        q = rng.uniform(lo, hi)
        for i in rng.choice(wide, size=int(rng.integers(1, min(3, len(wide)) + 1)), replace=False):
            q[i] = float(np.clip(values[(k + i) % len(values)], lo[i], hi[i]))
        out.append(q)
    return out


def _tight_selfmotion(arm: str, kb: Any, n: int) -> list[Q]:
    if len(kb.joints) != 7:
        return []
    lo, hi, has = ranges(kb)
    rng = _rng(arm, "tight_selfmotion")
    limited = np.flatnonzero(has)
    out = []
    for _ in range(n):
        q = rng.uniform(lo, hi)
        for i in rng.choice(
            limited, size=min(int(rng.integers(3, 5)), len(limited)), replace=False
        ):
            eps = (hi[i] - lo[i]) * 10 ** rng.uniform(-3.3, -1.3)
            q[i] = lo[i] + eps if rng.random() < 0.5 else hi[i] - eps
        out.append(q)
    return out


def near_singular(arm: str, kb: Any, n: int) -> list[Q]:
    """Coordinate descent on sigma_min(J): two sweeps over a 25-point grid per
    joint from a seeded uniform start; every other pose is then nudged off the
    minimiser. Only the regeneration script calls this (see module doc)."""
    lo, hi, _ = ranges(kb)
    rng = _rng(arm, "near_singular")
    nudges = (0.0, 1e-8, 0.0, 1e-6, 0.0, 1e-4)
    out = []
    for k in range(n):
        q = rng.uniform(lo, hi)
        for _sweep in range(2):
            best, best_i, best_v = sigma_min(kb, q), -1, 0.0
            for i in range(len(q)):
                for v in np.linspace(lo[i], hi[i], 25):
                    trial = q.copy()
                    trial[i] = v
                    s = sigma_min(kb, trial)
                    if s < best:
                        best, best_i, best_v = s, i, float(v)
            if best_i >= 0:
                q[best_i] = best_v
        nudge = nudges[k % len(nudges)]
        if nudge:
            q = np.clip(q + nudge * rng.standard_normal(len(q)), lo, hi)
        out.append(q)
    return out


