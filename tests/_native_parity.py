@cache
def _pose_data() -> dict[str, Any]:
    data: dict[str, Any] = json.loads(POSES_FILE.read_text())
    return data


@cache
def _full_poses(arm: str) -> dict[str, list[Q]]:
    kb = module(arm)._KB
    out = {s: gen(arm, kb, FULL[s]) for s, gen in _GENERATED.items()}
    out["near_singular"] = [np.array(q) for q in _pose_data()["arms"][arm]["near_singular"]]
    return out


def poses(arm: str, tier: str) -> list[tuple[str, Q]]:
    """``(pose id, q)`` for the tier. A pose id is ``"<stratum>/<index>"`` in
    the full tier, so a failure names a pose both tiers share."""
    full = _full_poses(arm)
    ids = [f"{s}/{k}" for s in FULL for k in range(min(TIERS[tier][s], len(full[s])))]
    if tier == "fast":  # every platform's witnesses (scripts/regen_native_parity.py)
        for pins in _pose_data()["arms"][arm]["fast_pins"].values():
            ids += [p for p in pins if p not in ids]
    out = []
    for pid in ids:
        s, k = pid.split("/")
        out.append((pid, full[s][int(k)]))
    return out


# ------------------------------------------------------------------ matching


def _dist(a: Q, b: Q) -> NDArray[np.float64]:
    """Pairwise L-infinity distance, every joint on the circle."""
    d = (a[:, None, :] - b[None, :, :] + np.pi) % _TWO_PI - np.pi
    return np.asarray(np.max(np.abs(d), axis=2))


def unmatched(src: Q, dst: Q, tol: float) -> list[int]:
    """Rows of ``src`` with no row of ``dst`` within ``tol``."""
    if not len(src):
        return []
    if not len(dst):
        return list(range(len(src)))
    return [int(i) for i in np.flatnonzero(~np.any(_dist(src, dst) <= tol, axis=1))]


def _limit_excess(q: Q, lo: Q, hi: Q, has: NDArray[np.bool_]) -> float:
    """How far the configuration's nearest in-range representative lies
    outside its limits (<= 0 when inside); raw-mode coordinates are only one
    representative, so every 2*pi shift is tried."""
    worst = -np.inf
    for i in np.flatnonzero(has):
        k = np.round((np.clip(q[i], lo[i], hi[i]) - q[i]) / _TWO_PI)
        best = min(
            max(lo[i] - v, v - hi[i]) for v in (q[i] + _TWO_PI * (k + d) for d in (-1, 0, 1))
        )
        worst = max(worst, best)
    return float(worst)


# ----------------------------------------------------------------- the oracle


@dataclass(frozen=True)
class Adjudication:
    """The oracle's branch set at one pose (joint limits removed)."""

    stabilized: bool
    branches: Q

    def verdict(self, q: Q, recovered_by: Q) -> str | None:
        """Why a solution one backend lacks is not a gap, or None if it is.

        ``recovered_by`` is the other backend's raw analytic set."""
        if not self.stabilized:
            return "the oracle did not stabilise: not a finite branch set here"
        if not len(self.branches) or unmatched(q[None], self.branches, ADJ_TOL):
            return "not an oracle branch"
        b = self.branches[int(np.argmin(_dist(q[None], self.branches)[0]))]
        if not unmatched(b[None], recovered_by, ADJ_TOL):
            return "a duplicate of a branch the other backend returns"
        return None


@cache
def _oracle_file() -> dict[str, Any]:
    if not USE_COMMITTED_ORACLE or not ORACLE_FILE.exists():
        return {}
    data: dict[str, Any] = json.loads(ORACLE_FILE.read_text())
    return data


def run_oracle(arm: str, q: Q) -> Adjudication:
    from tests._branch_oracle import enumerate_branches

    m = module(arm)
    kb = copy.deepcopy(m._KB)
    for j in kb.joints:  # every branch, not only those an in-limits start reaches
        j.limits = None
    res = enumerate_branches(kb, np.asarray(m.fk(q), dtype=np.float64))
    dof = len(kb.joints)
    return Adjudication(res.stabilized, np.array(res.branches).reshape(-1, dof))


@cache
def adjudicate(arm: str, pid: str) -> Adjudication:
    """The committed adjudication, or a live oracle run for a pose the
    committed file lacks (a platform whose numerics raise a gap elsewhere)."""
    rec = _oracle_file().get("arms", {}).get(arm, {}).get(pid)
    if rec is not None:
        dof = len(module(arm)._KB.joints)
        return Adjudication(rec["stabilized"], np.array(rec["branches"]).reshape(-1, dof))
    q = dict(poses(arm, "full"))[pid]
    return run_oracle(arm, q)


# ---------------------------------------------------------------- evaluation


@dataclass(frozen=True)
class Gap:
    cls: str  # a CLASSES key, or NEW
    check: str  # soundness | emptiness | coverage | reverse
    mode: str  # limits | raw
    pose: str
    detail: str

    def __str__(self) -> str:
        return f"[{self.cls}] {self.check} ({self.mode}) at {self.pose}: {self.detail}"


@dataclass
class Report:
    forward: list[Gap] = field(default_factory=list)
    reverse: list[Gap] = field(default_factory=list)
    oracle_poses: set[str] = field(default_factory=set)  # poses the oracle judged


def _solve(m: Any, t: Q, *, limits: bool, native: bool, rescue: bool) -> tuple[Q, Q]:
    """The solutions' joint vectors and their reported ``fk_residual``s."""
    sols = m.solve(
        t, respect_limits=limits, native=native, allow_rescue=rescue, enumerate_windings=False
    )
    dof = len(m._KB.joints)
    qs = np.array([np.asarray(s.q, dtype=np.float64) for s in sols]).reshape(-1, dof)
    return qs, np.array([s.fk_residual for s in sols], dtype=np.float64)


class _Pose:
    """One pose's solve sets and the classification rules that read them."""

    def __init__(self, arm: str, pid: str, q: Q, rep: Report) -> None:
        self.arm, self.pid, self.rep = arm, pid, rep
        self.m = module(arm)
        self.kb = self.m._KB
        self.dof = len(self.kb.joints)
        self.fam = family(arm)
        self.tol = MATCH_TOL[self.dof]
        self.lo, self.hi, self.has = ranges(self.kb)
        self.t = np.asarray(self.m.fk(q), dtype=np.float64)
        self.floor = same_root_floor(self.t)
        # (mode, backend, rescue) -> solutions, and their reported residuals
        solved = {
            (mode, backend, rescue): _solve(
                self.m, self.t, limits=mode == "limits", native=backend == "native", rescue=rescue
            )
            for mode in ("limits", "raw")
            for backend in ("native", "python")
            for rescue in (True, False)
        }
        self.sets = {key: qs for key, (qs, _) in solved.items()}
        self.residuals = {key: res for key, (_, res) in solved.items()}
        # d. see SEVEN_R_SINGULAR
        self.coverage_defined = self.dof == 6 or sigma_min(self.kb, q) >= SEVEN_R_SINGULAR

    def fk_err(self, q: Q) -> float:
        return float(np.linalg.norm(self.m.fk(q) - self.t))

    def lacks(self, q: Q, mode: str, other: str) -> str | None:
        """The class of an analytic solution the ``other`` backend's analytic
        set lacks in ``mode``, or None when that is not a gap."""
        own = "python" if other == "native" else "native"
        other_raw = self.sets[("raw", other, False)]
        if mode == "limits":
            hits = [o for o in other_raw if not unmatched(q[None], o[None], self.tol)]
            if any(_limit_excess(o, self.lo, self.hi, self.has) > _LIMIT_BAND for o in hits):
                # The other backend has it just across a limit, beyond the band
                # within which it would have put it on the limit (#624).
                return "F"
            if unmatched(q[None], self.sets[("raw", own, False)], self.tol):
                # Not in its own raw set: its in-limits resolver produced it.
                if other == "native" and self.fam.startswith("seven_r.spherical_shoulder"):
                    return "A"
                if other == "native" and self.fam == "seven_r.srs_polished":
                    return "I"
                return NEW
            if hits:
                return NEW  # the other backend has it inside the limits, yet dropped it
        if self.dof == 6 and self.excused(q, other_raw):
            return None
        if other == "python":
            return "J"
        return "G" if self.fam == "jointlock.hp" else "E"

    def excused(self, q: Q, other_raw: Q) -> bool:
        """Whether a 6R solution the other backend lacks is not a missing branch.

        1. The other backend returns the same root at its own accuracy, by the
           #604 midpoint test (FK stays closed between the two). Near a
           singularity a root is ill-conditioned, and two FK-closing copies of
           it can lie far beyond the match radius.
        2. A regular root (J full rank, and its FK error moves it far less than
           the match radius) is an isolated branch by the implicit function
           theorem, so it is never excused.
        3. Near a singular root, the oracle decides (``Adjudication.verdict``).
        """
        r = self.fk_err(q)
        if any(
            is_same_root(q, r, o, self.fk_err(o), self.m.fk, self.t, self.floor) for o in other_raw
        ):
            return True
        s = sigma_min(self.kb, q)
        if s >= REGULAR_SIGMA and r / s <= ADJ_TOL / 10:
            return False
        self.rep.oracle_poses.add(self.pid)
        return adjudicate(self.arm, self.pid).verdict(q, other_raw) is not None

    def across_limit(self, want: Q, other: str) -> bool:
        """Whether every solution of ``want`` is in the ``other`` backend's raw
        set (rescue included) just outside a joint limit: the two backends
        rescued the same configurations, and only the limit filter split them."""
        other_raw = self.sets[("raw", other, True)]
        for q in want:
            hits = [o for o in other_raw if not unmatched(q[None], o[None], self.tol)]
            if not any(_limit_excess(o, self.lo, self.hi, self.has) > _LIMIT_BAND for o in hits):
                return False
        return True

    def check(self, mode: str) -> None:
        pid, rep = self.pid, self.rep
        nat, py = self.sets[(mode, "native", True)], self.sets[(mode, "python", True)]
        nat_a, py_a = self.sets[(mode, "native", False)], self.sets[(mode, "python", False)]

        # a. soundness
        for x in np.vstack([nat, nat_a]):
            r = self.fk_err(x)
            if r > FK_TOL:
                rep.forward.append(Gap(NEW, "soundness", mode, pid, f"FK {r:.1e} at {x.tolist()}"))
            if mode == "limits":
                ex = _limit_excess(x, self.lo, self.hi, self.has)
                if ex > LIMIT_SLACK:
                    rep.forward.append(
                        Gap(
                            "B",
                            "soundness",
                            mode,
                            pid,
                            f"{ex:.1e} rad outside the limits: {x.tolist()}",
                        )
                        if self.fam == "seven_r.srs_polished"
                        else Gap(NEW, "soundness", mode, pid, f"{ex:.1e} rad outside: {x.tolist()}")
                    )

        # a. the reported residual is the returned configuration's (#645)
        for backend, out in (("native", rep.forward), ("python", rep.reverse)):
            for rescue in (True, False):
                key = (mode, backend, rescue)
                for x, reported in zip(self.sets[key], self.residuals[key], strict=True):
                    actual = self.fk_err(x)
                    if abs(reported - actual) > RESIDUAL_TOL:
                        out.append(
                            Gap(
                                NEW,
                                "soundness",
                                mode,
                                pid,
                                f"{backend} fk_residual {reported:.1e}, actual {actual:.1e} "
                                f"at {x.tolist()}",
                            )
                        )

        # b. emptiness, and e. its reverse
        for got, want, want_a, other, out in (
            (nat, py, py_a, "native", rep.forward),
            (py, nat, nat_a, "python", rep.reverse),
        ):
            if len(got) or not len(want):
                continue
            if len(want_a):
                cls = self.lacks(want_a[0], mode, other)
                if cls is None:
                    continue
            elif mode == "limits" and self.across_limit(want, other):
                # Both rescues found it, at a joint limit: an exact-limit tie.
                cls = "F"
            elif other == "native":  # every Python solution came from its rescue
                cls = "C" if self.fam == "jointlock.rr" else "D"
            else:
                cls = "D"
            who = "native" if other == "native" else "Python"
            out.append(
                Gap(
                    cls, "emptiness", mode, pid, f"{who} [] vs {len(want)} ({len(want_a)} analytic)"
                )
            )

        # c/d. coverage of the analytic sets, and e. its reverse (6R only: a
        # redundant 7R backend may sample the self-motion more densely by
        # design, #550)
        if not self.coverage_defined:
            return
        pairs = [(py_a, nat_a, "native", rep.forward)]
        if self.dof == 6:
            pairs.append((nat_a, py_a, "python", rep.reverse))
        for src, dst, other, out in pairs:
            for i in unmatched(src, dst, self.tol):
                cls = self.lacks(src[i], mode, other)
                if cls is not None:
                    who = "native" if other == "native" else "Python"
                    out.append(Gap(cls, "coverage", mode, pid, f"{who} lacks {src[i].tolist()}"))


@cache
def evaluate(arm: str, tier: str) -> Report:
    """Every gap on the tier's poses, each attributed to a class."""
    rep = Report()
    for pid, q in poses(arm, tier):
        pose = _Pose(arm, pid, q, rep)
        for mode in ("limits", "raw"):
            pose.check(mode)
    return rep
