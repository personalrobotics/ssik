"""Native-vs-Python parity gate: poses, evaluation and gap classes (#626).

Since #554 the native backend is the default solve path, so every shipped
arm's native ``solve()`` is held to the Python path, and where the two
disagree on a 6R arm, to the chart-free branch oracle (``tests/_branch_oracle``).

Poses
    Every arm gets the same deterministic strata (``poses``). ``uniform`` is
    in-limits uniform sampling; the others target the regions where the two
    backends' numerics diverge and uniform sampling almost never lands:

    - ``near_limit``: one to three limited joints placed *exactly* at a limit,
      or 1e-9 / 1e-6 inside it (``LIMIT_OFFSETS``, cycled).
    - ``near_singular``: a seeded coordinate descent on sigma_min(J) over a
      per-joint grid (the grid includes both limits), then every other pose
      nudged off the minimiser by 1e-8, 1e-6 or 1e-4. The descent is an
      optimisation whose result can move by an ulp between platforms, so its
      output is committed (``POSES_FILE``, regenerated by
      ``scripts/regen_native_parity.py``) instead of recomputed.
    - ``at_pi``: joints whose range reaches +-pi placed at +-pi or 1e-9 inside.
    - ``tight_selfmotion`` (7R only): three or four joints 0.05 % to 5 % of
      their range from a limit, which squeezes the in-limit self-motion.

    The other strata are drawn from ``numpy.random.default_rng`` seeded with
    ``SEED`` and the arm and stratum names, so they reproduce exactly.

Assertions (``evaluate``), in the default (``respect_limits=True``) and raw
(``respect_limits=False``) modes, geometric set only (``enumerate_windings=
False``: winding lifts are a deterministic function of the limits applied after
the solve, tested in ``tests/test_winding_enumeration.py``):

    a. soundness: every native solution closes FK within the default policy's
       ``subproblem_numerical`` (the documented closure contract), and in the
       default mode lies within the joint limits widened by ``LIMIT_SLACK``;
       every solution of either backend reports the ``fk_residual`` of the
       ``q`` it returns, within ``RESIDUAL_TOL`` (#645);
    b. emptiness: the default solve is never empty on native while it is not
       on Python;
    c. 6R coverage: the analytic solve (``allow_rescue=False``) on native
       contains every analytic Python solution, unless ``_Pose.excused``
       shows the missing one is not a branch native lacks;
    d. 7R coverage: the same, except at a kinematic singularity
       (``SEVEN_R_SINGULAR``), where the backends sample a larger continuum
       at their own points and only emptiness is asserted;
    e. the reverse direction of b and c (Python covers native), for 6R.

Solutions match within ``MATCH_TOL`` (L-infinity, on the circle). Every
violation is attributed to one class of ``CLASSES`` by ``_Pose.lacks``, from
evidence that does not depend on which test is asking: whether the missing
solution came from its backend's rescue or in-limits resolver, whether the
other backend's raw set has it just across a limit, and the arm's solver
family. A violation no rule explains is class ``NEW``, which no test expects.
"""

